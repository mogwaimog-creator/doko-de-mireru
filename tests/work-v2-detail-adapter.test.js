'use strict';
const assert=require('node:assert/strict');
const {toBasicTmdbDetail}=require('../api/_work-v2-detail-adapter');
const base={schemaVersion:2,type:'movie',id:123,title:'作品',originalTitle:'Original',releaseDate:'2020-01-02',posterPath:'/p.jpg',overview:'紹介',runtimeMinutes:110,genres:['ドラマ'],director:{id:1,name:'監督'},cast:[{id:2,name:'出演'}],rating:7.5};
const movie=toBasicTmdbDetail(base);
assert.equal(movie.title,'作品');
assert.equal(movie.release_date,'2020-01-02');
assert.equal(movie.runtime,110);
assert.equal(movie.credits.crew[0].job,'Director');
assert.equal(movie.credits.cast[0].id,2);
assert.equal(movie.poster_path,'/p.jpg');
assert.equal(movie.vote_average,7.5);
const tv=toBasicTmdbDetail({...base,type:'tv',seasonCount:2,episodeCount:18,status:'Ended',seasons:[{seasonNumber:1,name:'第1期',episodeCount:9,airDate:'2020-01-02'}]});
assert.equal(tv.first_air_date,'2020-01-02');
assert.equal(tv.number_of_seasons,2);
assert.equal(tv.number_of_episodes,18);
assert.equal(tv.seasons[0].season_number,1);
assert.equal(tv.episode_run_time[0],110);
assert.equal(tv.status,'Ended');
assert.throws(()=>toBasicTmdbDetail({}),/Invalid/);
console.log('work v2 basic detail adapter tests passed');
